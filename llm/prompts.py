def get_emotion_analysis_prompt(emotion_tags_str: str) -> str:
    """
    生成情绪分析提示词
    
    Args:
        emotion_tags_str: 情感标签字符串（格式：tag1(中文1)、tag2(中文2)...）
    
    Returns:
        情绪分析提示词
    """
    return f"""请分析以下文本的情绪状态，并返回一个 **有效的 JSON 对象**，格式严格符合要求。

可用情绪标签：{emotion_tags_str}

输出要求：
1. **emotion_tag**：从上述标签中选出最符合文本情绪的一个（仅返回英文标签，如 "happy"、"sad" 等）。
2. **emotion_intensity**：情绪强度（1–10 的整数），1 表示非常轻微，10 表示极其强烈。
3. **reason**：用一行简短自然的语言解释选择该标签与强度的原因。

返回格式（必须严格遵守 JSON 规范）：
{{
  "emotion_tag": "标签（英文）",
  "emotion_intensity": 整数值,
  "reason": "简短说明"
}}

仅输出 JSON，不要添加其他说明或文本。

待分析文本："""


