def get_greeting_prompt(history_summary: str, username: str = "朋友") -> str:
    """
    生成问候语提示词
    
    Args:
        history_summary: 用户历史摘要
        username: 用户名
    
    Returns:
        问候语生成提示词
    """
    return f"""你是一个温暖的情绪伙伴，现在要向用户{username}打招呼。

用户的最近几次情绪记录：
{history_summary}

请生成一条温暖、自然的问候语，要求：
1. 体现你记得 TA 之前分享的内容
2. 表达关心和延续性
3. 简短亲切（30-50字）
4. 可以提一个开放式的问题

问候语："""


def get_proactive_care_prompt(history_summary: str, username: str = "朋友", max_messages: int = 8) -> str:
    """
    生成主动关怀消息提示词
    
    Args:
        history_summary: 用户历史摘要
        username: 用户名
        max_messages: 最多生成的消息数量
    
    Returns:
        主动关怀消息生成提示词
    """
    return f"""你是一个温暖的情绪伙伴，基于用户{username}的历史情绪记录，生成{max_messages}条主动关怀消息。

用户的历史情绪记录：
{history_summary}

要求：
1. 每条消息都要基于用户曾经分享的具体事件或话题
2. 体现时间延续性（如"那个让你焦虑的考试过去了，感觉如何？"）
3. 表达关心和跟进，而不是简单的问候
4. 语言温暖自然，简短（20-40字）
5. 每条消息关注不同的历史话题
6. 可以是跟进式询问、关心式询问或鼓励式表达

请生成{max_messages}条关怀消息，每条消息一行，格式如下：
1. 第一条关怀消息
2. 第二条关怀消息
..."""


