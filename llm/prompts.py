def get_emotion_analysis_prompt(emotion_tags_str: str) -> str:
    """
    生成情绪分析提示词
    
    Args:
        emotion_tags_str: 情感标签字符串（格式：tag1(中文1)、tag2(中文2)...）
    
    Returns:
        情绪分析提示词
    """
    return f"""请分析以下文本的情感状态，并返回 JSON 格式的结果。

支持的情感标签：{emotion_tags_str}

要求：
1. emotion_tag: 从上述标签中选择最匹配的一个（只返回英文标签，如 happy、sad 等）
2. emotion_intensity: 情绪强度（1-10的整数），1表示非常轻微，10表示极其强烈
3. reason: 简短说明（一句话）为什么选择这个标签和强度

返回格式（必须是有效的 JSON）：
{{
  "emotion_tag": "标签",
  "emotion_intensity": 强度值,
  "reason": "原因说明"
}}

待分析文本："""


